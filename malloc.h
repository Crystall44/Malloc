#ifndef MY_MALLOC_H
#define MY_MALLOC_H

#include <stddef.h>
#include <stdint.h>

// Собственная реализация динамического распределения памяти

// Особенности:
// Алгоритм поиска best-fit для уменьшения фрагментации
// Слияние соседних свободных блоков при освобождении
// Защита от повреждений: magic cookie в заголовке блока
// Выравнивание блоков по 16 байт
// Выделение памяти через Windows API (HeapAlloc)

// Основные функции

// Выделяет блок памяти размером size байт. Память не инициализируется
void* my_malloc(size_t size);

// Освобождает ранее выделенный блок. При освобождении сливается с соседями
void my_free(void* ptr);

// Выделяет обнулённую память под массив из nmemb элементов по size байт
// Память инициализируется нулями
void* my_calloc(size_t nmemb, size_t size);

// Изменяет размер ранее выделенного блока
// При увеличении размера выделяет новый блок, копирует данные и освобождает старый
void* my_realloc(void* ptr, size_t size);


// Отладочные функции

// Выводит содержимое списка свободных блоков: адрес, размер, состояние (свободен/занят)
void print_free_lists(void);

// Выводит сводную статистику использования кучи
void print_heap_stats(void);

// Возвращает общий объём свободной памяти в байтах
size_t get_total_free_memory(void);

// Возвращает количество свободных блоков
size_t get_free_block_count(void);

// Возвращает общий объём памяти, запрошенной у ОС с начала работы
size_t get_total_allocated_memory(void);

// Проверяет, является ли указатель валидным
int is_block_valid(void* ptr);

// Проверяет целостность всех блоков в куче
int validate_heap(void);

// Возвращает коэффициент внешней фрагментации в диапазоне[0; 1]
double get_fragmentation_ratio(void);

#endif