#ifndef MY_MALLOC_H
#define MY_MALLOC_H

#include <stddef.h>
#include <stdint.h>

// Собственная реализация динамического распределения памяти

// Особенности:
// Сегрегированные списки свободных блоков (4 уровня по размерам)
// Алгоритм поиска best-fit для уменьшения фрагментации
// Слияние соседних свободных блоков (O(1) благодаря footer)
// Возврат памяти операционной системе при освобождении конца кучи
// Выравнивание блоков по 16 байт (как в glibc)
// Защита от повреждений: magic cookie в заголовке и footer

// Основные функции

// Выделяет блок памяти размером size байт, память не инициализируется (может содержать мусор)
void* my_malloc(size_t size);

// Освобождает ранее выделенный блок памяти. Если ptr == NULL, ничего не делает
// При освобождении автоматически сливается с соседними свободными блоками
void my_free(void* ptr);

// Выделяет память под массив из nmemb элементов размером size каждый
// Память инициализируется нулями
void* my_calloc(size_t nmemb, size_t size);

// Изменяет размер ранее выделенного блока памяти
// Если ptr == NULL, работает как my_malloc(size), 
// Если size == 0, работает как my_free(ptr)
void* my_realloc(void* ptr, size_t size);


// Отладочные функции

// Выводит содержимое всех сегрегированных списков свободных блоков
void print_free_lists(void);

// Выводит сводную статистику использования кучи
void print_heap_stats(void);

// Возвращает общий объём свободной памяти в байтах
size_t get_total_free_memory(void);

// Возвращает общий объём памяти, запрошенной у ОС с начала работы
size_t get_total_allocated_memory(void);

// Проверяет целостность всех блоков в куче
int validate_heap(void);

// Возвращает коэффициент внешней фрагментации в диапазоне[0; 1]
double get_fragmentation_ratio(void);

#endif